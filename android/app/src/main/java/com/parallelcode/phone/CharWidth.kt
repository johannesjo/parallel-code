    private val COMBINING_ASTRAL = intArrayOf(
        0x10A01, 0x10A03, 0x10A05, 0x10A06, 0x10A0C, 0x10A0F, 0x10A38, 0x10A3A, 0x10A3F, 0x10A3F, 0x1D167, 0x1D169,
        0x1D173, 0x1D182, 0x1D185, 0x1D18B, 0x1D1AA, 0x1D1AD, 0x1D242, 0x1D244, 0xE0001, 0xE0001, 0xE0020, 0xE007F,
        0xE0100, 0xE01EF,
    )

    private val BMP = ByteArray(65536).also { t ->
        t.fill(1)
        t[0] = 0
        t.fill(0, 1, 32)
        t.fill(0, 127, 160)
        t.fill(2, 0x1100, 0x1160)
        t[0x2329] = 2
        t[0x232A] = 2
        t.fill(2, 0x2E80, 0xA4D0)
        t[0x303F] = 1
        t.fill(2, 0xAC00, 0xD7A4)
        t.fill(2, 0xF900, 0xFB00)
        t.fill(2, 0xFE10, 0xFE1A)
        t.fill(2, 0xFE30, 0xFE70)
        t.fill(2, 0xFF00, 0xFF61)
        t.fill(2, 0xFFE0, 0xFFE7)
        for (i in COMBINING.indices step 2) t.fill(0, COMBINING[i], COMBINING[i + 1] + 1)
    }

    fun of(codePoint: Int): Int = when {
        codePoint < 0x10000 -> BMP[codePoint].toInt()
        inRanges(codePoint, COMBINING_ASTRAL) -> 0
        codePoint in 0x20000..0x2FFFD || codePoint in 0x30000..0x3FFFD -> 2
        else -> 1
    }

    private fun inRanges(codePoint: Int, ranges: IntArray): Boolean {
        var lo = 0
        var hi = ranges.size / 2 - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            when {
                codePoint > ranges[mid * 2 + 1] -> lo = mid + 1
                codePoint < ranges[mid * 2] -> hi = mid - 1
                else -> return true
            }
        }
        return false
    }
}
