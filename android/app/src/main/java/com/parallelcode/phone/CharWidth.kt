/**
 * How many terminal cells a character takes, exactly as the desktop's terminal (xterm.js with its
 * default Unicode 6 widths, UnicodeV6) counts them, so lines wrap and columns line up as there.
 * Note that xterm 6 counts most emoji, even astral ones such as U+1F916, as one cell.
 */
