export type ProjectIconId = (typeof PROJECT_ICON_GROUPS)[number]['ids'][number];

export const PROJECT_ICON_IDS: readonly ProjectIconId[] = PROJECT_ICON_GROUPS.flatMap((g) => g.ids);

/** Returns the value as a known icon id, or undefined so unknown ids fall back to the square. */
export function sanitizeProjectIcon(value: unknown): ProjectIconId | undefined {
  return PROJECT_ICON_IDS.find((id) => id === value);
}
