import { beforeEach, describe, expect, it, vi } from 'vitest';

// Client suite: the unit suite renders Solid for the server, where effects never run.
const { mockStartRequest, mockIsTaskWorking } = vi.hoisted(() => ({
  mockStartRequest: vi.fn(),
  mockIsTaskWorking: vi.fn(),
}));

vi.mock('../lib/model-request', () => ({ startModelRequest: mockStartRequest }));
vi.mock('../lib/load-task-diff', () => ({
  loadTaskDiff: () => Promise.resolve({ rawDiff: '', cwd: '/wt' }),
  getTaskDiffBaseBranch: (_mode: string, base?: string) => base,
}));
vi.mock('./projects', () => ({ getProjectPath: () => '/repo' }));
vi.mock('./agentHookStatus', () => ({ getAgentHookStatus: () => null }));
vi.mock('./taskStatus', () => ({
  isTaskWorking: mockIsTaskWorking,
  getAgentOutputTail: () => 'screen text',
  normalizeCurrentFrame: (text: string) => text,
}));

import { store, setStore } from './core';
import { startTaskBriefWatcher } from './task-brief';
import type { Task } from './types';

const LONG =
  'I was thinking about how we could best improve our general setup, including GitHub replies';

beforeEach(() => {
  vi.clearAllMocks();
  setStore('taskBriefs', true);
  setStore('modelTaskNames', false);
  setStore('tasks', {
    t1: {
      id: 't1',
      name: 'Setup',
      projectId: 'p1',
      worktreePath: '/wt',
      gitIsolation: 'worktree',
      agentIds: ['agent-1'],
    } as unknown as Task,
  });
  mockStartRequest.mockReturnValue({
    result: Promise.resolve(JSON.stringify({ goal: 'Improve the setup', now: 'Starting' })),
    cancel: vi.fn(),
  });
});

async function startWorking(prompt: string): Promise<void> {
  setStore('tasks', 't1', 'savedInitialPrompt', prompt);
  setStore('taskOrder', ['t1']);
  mockIsTaskWorking.mockReturnValue(true);
  const stop = startTaskBriefWatcher();
  await vi.waitFor(() => expect(store.tasks.t1.briefStatus).toBeUndefined());
  stop();
}

describe('startTaskBriefWatcher', () => {
  it('briefs a task with a long prompt as it starts, so the goal is not the raw prompt', async () => {
    await startWorking(LONG);
    expect(mockStartRequest).toHaveBeenCalledOnce();
    expect(store.tasks.t1.brief?.brief.goal).toBe('Improve the setup');
  });

  it('waits for the turn to end when the prompt already reads as a goal', async () => {
    await startWorking('Fix the redirect');
    expect(mockStartRequest).not.toHaveBeenCalled();
  });

  it('still briefs the first turn when it changed no code and left only a screen', async () => {
    vi.useFakeTimers();
    try {
      setStore('tasks', 't1', 'savedInitialPrompt', LONG);
      setStore('taskOrder', ['t1']);
      mockIsTaskWorking.mockReturnValue(true);
      const stop = startTaskBriefWatcher();
      await vi.advanceTimersByTimeAsync(0);
      mockIsTaskWorking.mockReturnValue(false);
      setStore('taskOrder', ['t1']);
      await vi.advanceTimersByTimeAsync(5_000);
      stop();
      expect(mockStartRequest).toHaveBeenCalledTimes(2);
    } finally {
      vi.useRealTimers();
    }
  });

  it('leaves the title to the brief after the first turn, which knows the work', async () => {
    vi.useFakeTimers();
    try {
      setStore('modelTaskNames', true);
      setStore('tasks', 't1', 'nameIsAutoGenerated', true);
      setStore('tasks', 't1', 'savedInitialPrompt', LONG);
      setStore('taskOrder', ['t1']);
      mockIsTaskWorking.mockReturnValue(true);
      const reply = (title: string) => ({
        result: Promise.resolve(JSON.stringify({ title, goal: 'Improve the setup', now: 'x' })),
        cancel: vi.fn(),
      });
      mockStartRequest
        .mockReturnValueOnce(reply('From prompt'))
        .mockReturnValueOnce(reply('From work'));
      const stop = startTaskBriefWatcher();
      await vi.advanceTimersByTimeAsync(0);
      expect(store.tasks.t1.name).toBe('Setup');
      mockIsTaskWorking.mockReturnValue(false);
      setStore('taskOrder', ['t1']);
      await vi.advanceTimersByTimeAsync(5_000);
      stop();
      expect(store.tasks.t1.name).toBe('From work');
    } finally {
      vi.useRealTimers();
    }
  });

  it('briefs the first turn once the early brief, still being written when it ended, is done', async () => {
    vi.useFakeTimers();
    try {
      setStore('tasks', 't1', 'savedInitialPrompt', LONG);
      setStore('taskOrder', ['t1']);
      mockIsTaskWorking.mockReturnValue(true);
      let finishEarly = (_value: string) => {};
      mockStartRequest.mockReturnValueOnce({
        result: new Promise<string>((resolve) => (finishEarly = resolve)),
        cancel: vi.fn(),
      });
      const stop = startTaskBriefWatcher();
      await vi.advanceTimersByTimeAsync(0);
      mockIsTaskWorking.mockReturnValue(false);
      setStore('taskOrder', ['t1']);
      await vi.advanceTimersByTimeAsync(5_000);
      expect(mockStartRequest).toHaveBeenCalledOnce();
      finishEarly(JSON.stringify({ goal: 'Improve the setup', now: 'Starting' }));
      await vi.advanceTimersByTimeAsync(0);
      stop();
      expect(mockStartRequest).toHaveBeenCalledTimes(2);
    } finally {
      vi.useRealTimers();
    }
  });
});
