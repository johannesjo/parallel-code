import {
  TASK_NAME_MODELS,
  buildTaskNamePrompt,
  parseModelTaskName,
} from '../../electron/shared/task-name-model';
import { startModelRequest } from '../lib/model-request';
import { warn as logWarn } from '../lib/log';
import { setStore, store } from './core';
import { updateTaskName } from './tasks';
import type { Task } from './types';

/**
 * Replaces a prompt-derived task name with a short title from the chosen cheap
 * model (Haiku or Luna), when the user opted in. The task starts with the heuristic name, so this never delays
 * creation; the branch keeps that name, since renaming a live worktree's
 * branch would pull it out from under the running agent.
 *
 * A task opened from Super Productivity is already linked here and keeps that
 * task's title. One created here links later and receives the model title
 * through the usual rename sync.
 */
export async function nameTaskWithModel(taskId: string, prompt: string): Promise<void> {
  const task = store.tasks[taskId];
  if (!store.modelTaskNames || !prompt.trim() || !task?.worktreePath) return;
  if (task.superProductivity) return;
  try {
    const reply = await startModelRequest({
      prompt: buildTaskNamePrompt(prompt),
      cwd: task.worktreePath,
      settings: TASK_NAME_MODELS[store.taskNameModel],
      agentEnvFiles: store.agentEnvFiles,
      projectId: task.projectId,
      purpose: 'task-name',
    }).result;
    const name = parseModelTaskName(reply);
    if (!name) {
      logWarn(
        'tasks',
        'Model task naming returned no usable title; keeping the prompt-derived name',
        {
          reply: reply.slice(0, 200),
        },
      );
      return;
    }
    // The user may have renamed or closed the task while the model was answering.
    if (!store.tasks[taskId]?.nameIsAutoGenerated) return;
    updateTaskName(taskId, name);
    setStore('tasks', taskId, 'nameFromModel', true);
  } catch (err) {
    logWarn('tasks', 'Model task naming failed; keeping the prompt-derived name', {
      err: String(err),
    });
  }
}

/**
 * Whether the next brief may retitle the task: the user opted into model names
 * and has not named it, and it does not follow a Super Productivity title.
 * The first brief knows the goal from the agent's work, not only the prompt.
 */
export function canRetitleFromBrief(task: Task | undefined): boolean {
  if (!store.modelTaskNames || !task || task.superProductivity) return false;
  return !!task.nameIsAutoGenerated || !!task.nameFromModel;
}

/** Applies a brief's title once; the rename marks the name as settled. */
export function retitleFromBrief(taskId: string, title: string): void {
  const name = parseModelTaskName(title);
  if (!name) {
    logWarn('tasks', 'Task brief returned no usable title; keeping the current name', { title });
    return;
  }
  if (!canRetitleFromBrief(store.tasks[taskId])) return;
  updateTaskName(taskId, name);
}
